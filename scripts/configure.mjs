import { readFileSync, writeFileSync } from "node:fs";
import { loadEnv } from "./env.mjs";
const root = new URL("../", import.meta.url);
const env = loadEnv(root);
const postcode = (env.ORIGIN_POSTCODE || "").trim().toUpperCase();
if (!postcode || postcode === "YOUR_POSTCODE") throw new Error("Set ORIGIN_POSTCODE in .env.local before configuring the app.");
let lat = env.ORIGIN_LATITUDE, lon = env.ORIGIN_LONGITUDE;
if (!lat || !lon) {
  const response = await fetch("https://api.postcodes.io/postcodes/" + encodeURIComponent(postcode), { signal: AbortSignal.timeout(8000) });
  const data = await response.json();
  if (!response.ok || !data.result) throw new Error("Could not resolve your configured postcode. Supply coordinates in .env.local or retry.");
  lat = String(data.result.latitude); lon = String(data.result.longitude);
}
if (![lat, lon].every(value => Number.isFinite(Number(value))) || Math.abs(Number(lat)) > 90 || Math.abs(Number(lon)) > 180) throw new Error("Invalid origin coordinates.");
const radius = Number(env.SEARCH_RADIUS_MILES || 40), maxDrive = Number(env.DEFAULT_MAX_DRIVE_MINUTES || 60);
if (!Number.isInteger(radius) || radius < 1 || radius > 100 || !Number.isInteger(maxDrive) || maxDrive < 30 || maxDrive > 90) throw new Error("Invalid search radius or maximum drive.");
function origin(value) {
  if (!value) return "";
  const url = new URL(value);
  if (url.protocol !== "https:" || url.pathname !== "/" || url.search || url.hash || url.username || url.password) throw new Error("Deployment origins must be HTTPS origins without paths or credentials.");
  return url.origin;
}
const lakebedOrigin = origin(env.LAKEBED_ORIGIN), domainOrigin = origin(env.CUSTOM_DOMAIN_ORIGIN);
function privateWrite(path, content) { writeFileSync(new URL(path, root), content, { mode: 0o600 }); }
privateWrite("app/.env.lakebed.server", Object.entries({ ORIGIN_POSTCODE: postcode, ORIGIN_LATITUDE: lat, ORIGIN_LONGITUDE: lon, SEARCH_RADIUS_MILES: radius, DEFAULT_MAX_DRIVE_MINUTES: maxDrive }).map(([k,v]) => `${k}=${v}`).join("\n") + "\n");
// Only public routing origins enter this ignored client module. Home location
// remains server-side, never in the compiled client bundle.
privateWrite("app/shared/local-domain-config.ts", `// Generated by scripts/configure.mjs; do not commit.\nexport const DOMAIN_CONFIG = ${JSON.stringify({lakebedOrigin, domainOrigin})} as const;\n`);
if (env.LAKEBED_DEPLOY_ID) privateWrite("app/lakebed.json", JSON.stringify({deployId:env.LAKEBED_DEPLOY_ID},null,2)+"\n");
if (domainOrigin && lakebedOrigin && env.CLOUDFLARE_ACCOUNT_ID) {
  const template = JSON.parse(readFileSync(new URL("domain/wrangler.jsonc", root), "utf8"));
  privateWrite("domain/wrangler.local.jsonc", JSON.stringify({...template, name:env.CLOUDFLARE_WORKER_NAME || template.name, account_id:env.CLOUDFLARE_ACCOUNT_ID, routes:[{pattern:new URL(domainOrigin).hostname,custom_domain:true}],vars:{LAKEBED_ORIGIN:lakebedOrigin,CUSTOM_DOMAIN_ORIGIN:domainOrigin}},null,2)+"\n");
}
console.log("Local configuration generated. Personal values were not printed.");
